import "server-only";
import { env } from "@/server/env";
import { LocalFsStorage } from "./local";
import { S3Storage } from "./s3";

/** Where file bytes live. Task logic only ever talks to this interface. */
export interface StorageAdapter {
  put(key: string, body: Uint8Array, contentType: string): Promise<void>;
  /** Bytes for streaming through the app (local), or null when the adapter serves via signed URLs. */
  read(key: string): Promise<Uint8Array | null>;
  /** A short-lived direct download URL, or null when the adapter can't produce one (local). */
  signedDownloadUrl(key: string, options: { fileName: string; contentType: string; inline: boolean }): Promise<string | null>;
  delete(key: string): Promise<void>;
}

/** Object keys are generated by the app; anything else is refused (no traversal, no user input). */
export const STORAGE_KEY_PATTERN = /^ws\/[0-9a-f-]{36}\/[0-9a-f-]{36}$/;

export function assertStorageKey(key: string): void {
  if (!STORAGE_KEY_PATTERN.test(key)) throw new Error("Invalid storage key");
}

let cached: { signature: string; adapter: StorageAdapter } | undefined;

export function storage(): StorageAdapter {
  const e = env();
  const driver = e.STORAGE_DRIVER ?? (e.NODE_ENV === "production" ? "s3" : "local");
  const signature = [driver, e.STORAGE_LOCAL_DIR, e.S3_ENDPOINT, e.S3_BUCKET, e.S3_ACCESS_KEY_ID].join("|");
  if (cached?.signature === signature) return cached.adapter;

  let adapter: StorageAdapter;
  if (driver === "s3") {
    if (!e.S3_ENDPOINT || !e.S3_BUCKET || !e.S3_ACCESS_KEY_ID || !e.S3_SECRET_ACCESS_KEY) {
      throw new Error("File storage isn't configured: set S3_ENDPOINT, S3_BUCKET, S3_ACCESS_KEY_ID, S3_SECRET_ACCESS_KEY");
    }
    adapter = new S3Storage({
      endpoint: e.S3_ENDPOINT,
      region: e.S3_REGION,
      bucket: e.S3_BUCKET,
      accessKeyId: e.S3_ACCESS_KEY_ID,
      secretAccessKey: e.S3_SECRET_ACCESS_KEY,
    });
  } else {
    if (e.NODE_ENV === "production" && e.EIGHTCORE_ALLOW_FILE_MAIL !== "1") {
      throw new Error("Local file storage isn't allowed in production (hosts like Netlify have no permanent disk)");
    }
    adapter = new LocalFsStorage(e.STORAGE_LOCAL_DIR);
  }
  cached = { signature, adapter };
  return adapter;
}

/** Best-effort removal of stored files (after their rows are gone). Failures are logged, not thrown. */
export async function discardStored(items: { storageKey: string }[]) {
  await Promise.all(
    items.map((item) =>
      storage()
        .delete(item.storageKey)
        .catch((error: unknown) => console.error("[storage] could not delete", item.storageKey, error)),
    ),
  );
}
